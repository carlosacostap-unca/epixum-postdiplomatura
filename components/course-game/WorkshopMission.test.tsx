import {useState} from 'react';
import {fireEvent,render,screen} from '@testing-library/react';
import {expect,it} from 'vitest';
import {WorkshopMission,type WorkshopLocation} from './WorkshopMission';
import {INITIAL_WORKSHOP,WORKSHOP_REASONS,REVISED_PLAN,FINAL_PLAN} from '@/lib/course-game/workshop';
it('recorre el caso sin aceptar supuestos ni completar antes de comprobar y justificar',()=>{
 function Demo(){const [p,set]=useState(INITIAL_WORKSHOP),[location,go]=useState<WorkshopLocation>('lucia');return <WorkshopMission key={location} location={location} progress={p} onChange={set} onGo={go}/>;}
 render(<Demo/>);
 fireEvent.click(screen.getByText('Confirmar la propuesta'));
 expect(screen.getByText(/Objetivo actual:/)).toHaveTextContent('Revisá el pedido');
 fireEvent.click(screen.getByText('Averiguar las condiciones reales'));
 fireEvent.click(screen.getByRole('button',{name:/Qué necesitamos lograr/}));
 fireEvent.click(screen.getByText('Ir con Mateo'));
 fireEvent.click(screen.getByRole('button',{name:/Con qué equipos/}));
 fireEvent.click(screen.getByText('Ir con Ana'));
 fireEvent.click(screen.getByRole('button',{name:/Qué experiencia/}));
 fireEvent.click(screen.getByText('Continuar en la notebook docente del Aula 1'));
 fireEvent.click(screen.getByText('Preparar un pedido con objetivo, datos y restricciones'));
 fireEvent.click(screen.getByText('Enviar el pedido revisado'));
 fireEvent.click(screen.getByText('Aceptar porque incorporó las condiciones'));
 expect(screen.queryByText('Continuar: probar la ventana de contexto')).not.toBeInTheDocument();
 fireEvent.click(screen.getByText('Comprobar tiempos y recursos'));
 fireEvent.click(screen.getByText('Continuar: probar la ventana de contexto'));
 expect(screen.queryByText('Generar la propuesta corregida')).not.toBeInTheDocument();
 fireEvent.click(screen.getByText('Abrir conversación nueva y pedir un ajuste'));
 fireEvent.click(screen.getByText('Compartir un resumen revisado'));
 fireEvent.click(screen.getByText('Generar la propuesta corregida'));
 fireEvent.click(screen.getByText('Volver con Lucía para justificar el plan'));
 expect(screen.getByText('Presentar la decisión fundamentada')).toBeDisabled();
 for(const reason of WORKSHOP_REASONS)fireEvent.click(screen.getByLabelText(reason));
 fireEvent.click(screen.getByText('Presentar la decisión fundamentada'));
 expect(screen.getByText('Plan revisado · misión completada')).toBeVisible();
 expect(REVISED_PLAN.reduce((n,row)=>n+row[1],0)).toBe(100);
 expect(FINAL_PLAN.reduce((n,row)=>n+row[1],0)).toBe(90);
 fireEvent.click(screen.getByText('Reiniciar demostración'));
 fireEvent.click(screen.getByText('Sí, reiniciar misión'));
 expect(screen.getByText(/Objetivo actual:/)).toHaveTextContent('Revisá el pedido');
 expect(screen.getByText('Diario del taller · 0/3 fuentes consultadas')).toBeVisible();
});
