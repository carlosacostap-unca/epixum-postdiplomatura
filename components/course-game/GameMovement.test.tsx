import { NODO_ENTRANCE, NODO_REAR_ENTRANCE } from '@/lib/course-game/neighborhood';
vi.mock('./useGameSchedule', () => ({ useGameSchedule: () => ({ clock: null, isOpen: () => true }) }));
import { act, fireEvent, render, screen } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';
import type { VillageState } from './phaser/village-engine';
import CourseMissionMap from './CourseMissionMap';
import { DEFAULT_CHARACTER } from '@/lib/course-game/onboarding';
const state = vi.hoisted(() => ({ current: null as VillageState | null }));
vi.mock('./PhaserVillage', () => ({ default: (props: VillageState) => { state.current = props; return <div />; } }));
const game = { courseId:'pilot',title:'Valle',courseTitle:'Cohorte 2',introduction:'',places:[{id:'a',name:'Nodo',title:'Clase A',date:'',href:'/class-a'}],missions:[],completed:0 };
describe('controles del personaje', () => {
  it.each(['botón','rueda','touchpad','pellizco'])('centra al personaje incluso cerca del borde al hacer zoom con %s',gesture=>{
    render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER}/>);
    const viewport=screen.getByLabelText('Mapa del valle'),map=viewport.firstElementChild as HTMLElement;
    Object.defineProperties(viewport,{clientWidth:{value:480},clientHeight:{value:600}});
    Object.defineProperties(map,{offsetWidth:{get:()=>parseFloat(map.style.width)},offsetHeight:{get:()=>parseFloat(map.style.height)},offsetLeft:{value:240},offsetTop:{value:300}});
    const position={x:640,y:9};
    act(()=>state.current?.onPosition?.(position));
    viewport.scrollLeft=0;viewport.scrollTop=0;
    if(gesture==='botón') fireEvent.click(screen.getByRole('button',{name:'Acercar mapa'}));
    else if(gesture==='pellizco') {
      const pointer=(type:string,id:number,x:number)=>{
        const event=new Event(type,{bubbles:true});Object.assign(event,{pointerType:'touch',pointerId:id,clientX:x,clientY:100});fireEvent(viewport,event);
      };
      pointer('pointerdown',1,100);pointer('pointerdown',2,200);pointer('pointermove',2,250);
    } else fireEvent.wheel(viewport,{deltaY:-50,ctrlKey:gesture==='touchpad',clientX:20,clientY:20});
    expect(map.offsetWidth).toBeGreaterThan(1920);
    expect(position.x/960*map.offsetWidth+map.offsetLeft-viewport.scrollLeft).toBeCloseTo(240);
    expect(position.y/960*map.offsetHeight+map.offsetTop-viewport.scrollTop).toBeCloseTo(300);
  });
  it('incluye los márgenes del lienzo al seguir al personaje hasta el borde sur',()=>{
    render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER}/>);
    const viewport=screen.getByLabelText('Mapa del valle'),map=viewport.firstElementChild!;
    Object.defineProperties(viewport,{clientWidth:{value:480},clientHeight:{value:600}});
    Object.defineProperties(map,{offsetWidth:{value:1920},offsetHeight:{value:1920},offsetTop:{value:80},offsetLeft:{value:80}});
    act(()=>state.current?.onPosition?.({x:640,y:200}));
    expect(viewport.scrollLeft).toBe(1120);expect(viewport.scrollTop).toBe(180);
    act(()=>state.current?.onPosition?.({x:640,y:9}));
    expect(viewport.scrollTop).toBe(0);
    expect(80+(9-34)*2-viewport.scrollTop).toBeGreaterThanOrEqual(0);
  });
  it('conserva el lado de entrada y salida del Nodo',()=>{
    render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER}/>);
    act(()=>state.current?.onEnter?.('rear'));
    expect(state.current?.spawn).toEqual({x:240,y:106});
    fireEvent.click(screen.getByRole('button',{name:'Salir por detrás del Nodo'}));
    expect(state.current?.destination?.()).toEqual({x:240,y:52});
    act(()=>state.current?.onExit?.('rear'));
    expect(state.current?.spawn).toEqual({x:NODO_REAR_ENTRANCE.x,y:NODO_REAR_ENTRANCE.y-30});
    expect(screen.getByLabelText('Mapa del valle')).toBeVisible();
    act(()=>state.current?.onEnter?.('front'));
    expect(state.current?.spawn).toEqual({x:240,y:270});
  });
  it('centra la cámara en el personaje y la limita a los bordes del mundo ampliado',()=>{
    render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER}/>);
    const viewport=screen.getByLabelText('Mapa del valle');
    const map=viewport.firstElementChild!;
    Object.defineProperties(viewport,{clientWidth:{value:480},clientHeight:{value:600}});
    Object.defineProperties(map,{offsetWidth:{value:1920},offsetHeight:{value:1920},offsetTop:{value:0}});
    act(()=>state.current?.onPosition?.({x:500,y:600}));
    expect(viewport.scrollLeft).toBeCloseTo(760);expect(viewport.scrollTop).toBe(900);
    act(()=>state.current?.onPosition?.({x:950,y:950}));
    expect(viewport.scrollLeft).toBe(1440);expect(viewport.scrollTop).toBe(1320);
    act(()=>state.current?.onPosition?.({x:10,y:40}));
    expect(viewport.scrollLeft).toBe(0);expect(viewport.scrollTop).toBe(0);
  });
  it('abre la conversación al activar al perro y pausa el movimiento',()=>{
    render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER}/>);
    act(()=>state.current?.onCompanionPosition?.({x:220,y:240}));
    const dog=screen.getByRole('button',{name:'Hablar con tu perro robot'});
    fireEvent.keyDown(screen.getByLabelText('Mapa del valle'),{key:'w'});
    fireEvent.click(dog);
    expect(screen.getByRole('dialog',{name:'Tu perro robot'})).toBeVisible();
    expect(state.current?.movementLocked).toBe(true);
    expect(state.current?.input?.().up).toBe(false);
    const reveal=screen.queryByRole('button',{name:/Mostrar texto completo/});
    if(reveal) fireEvent.click(reveal);
    fireEvent.click(screen.getByRole('button',{name:'¿Dónde voy ahora?'}));
    expect(screen.getByRole('log')).toHaveTextContent('entrada del Nodo');
  });
  it('convierte clic y tap a coordenadas del mundo, ignora arrastres y cancela al usar teclado o menú', () => {
    render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER} />);
    const viewport = screen.getByLabelText('Mapa del valle');
    const map = viewport.firstElementChild as HTMLElement;
    vi.spyOn(map,'getBoundingClientRect').mockReturnValue({left:-100,top:80,width:960,height:640} as DOMRect);
    const pointer = (type: string,x:number,y:number,pointerType='mouse') => {
      const event = new Event(type,{bubbles:true});
      Object.assign(event,{pointerId:1,isPrimary:true,button:0,clientX:x,clientY:y,pointerType});
      fireEvent(map,event);
    };
    pointer('pointerdown',380,400); pointer('pointerup',380,400);
    expect(state.current?.destination?.()).toEqual({x:480,y:480});
    fireEvent.keyDown(viewport,{key:'w'});
    expect(state.current?.destination?.()).toBeNull();
    pointer('pointerdown',380,400,'touch'); pointer('pointermove',400,400,'touch'); pointer('pointerup',380,400,'touch');
    expect(state.current?.destination?.()).toBeNull();
    pointer('pointerdown',380,400,'touch'); pointer('pointerup',380,400,'touch');
    expect(state.current?.destination?.()).toEqual({x:480,y:480});
    fireEvent.click(screen.getByRole('button',{name:/Menú/}));
    expect(state.current?.destination?.()).toBeNull();
  });
  it('libera teclas al soltar y perder foco, y separa pausa ambiental del movimiento', () => {
    render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER} loadBoard={async()=>({success:true,content:{title:'Clase A',description:'<p>Contenido en la pizarra</p>',resources:[]}})} />);
    const map = screen.getByLabelText('Mapa del valle');
    expect(state.current?.paused).toBe(true);
    expect(state.current?.movementLocked).toBe(false);
    fireEvent.keyDown(map,{key:'w'}); expect(state.current?.input?.().up).toBe(true);
    fireEvent.keyUp(map,{key:'w'}); expect(state.current?.input?.().up).toBe(false);
    fireEvent.keyDown(map,{key:'ArrowRight'}); fireEvent(window,new Event('blur'));
    expect(state.current?.input?.().right).toBe(false);
  });
  it('entrar bloquea el movimiento y cerrar no vuelve a entrar', () => {
    render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER} loadBoard={async()=>({success:true,content:{title:'Clase A',description:'<p>Contenido en la pizarra</p>',resources:[]}})} />);
    fireEvent.keyDown(screen.getByLabelText('Mapa del valle'),{key:'w'});
    act(()=>state.current?.onEnter?.());
    expect(screen.getByLabelText('Interior del Nodo')).toBeVisible();
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
    act(()=>state.current?.onRoom?.(0));
    expect(screen.getByLabelText('Interior del aula')).toBeVisible();
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
    expect(screen.getByRole('button',{name:'Acercate a la pizarra'})).toBeDisabled();
    fireEvent.keyDown(screen.getByLabelText('Interior del aula'),{key:'e'});
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
    act(()=>state.current?.onPosition?.({x:240,y:120}));
    fireEvent.keyDown(screen.getByLabelText('Interior del aula'),{key:'e'});
    expect(screen.getByRole('dialog',{name:'Clase A'})).toBeVisible();
    expect(state.current?.movementLocked).toBe(true);
    expect(state.current?.input?.().up).toBe(false);
    fireEvent.click(screen.getByRole('button',{name:'Cerrar y volver al juego'}));
    expect(state.current?.movementLocked).toBe(false);
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
  });
  it('E exige proximidad al Nodo y el tutorial bloquea caminar', async () => {
    const view = render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER} loadBoard={async()=>({success:true,content:{title:'Clase A',description:'<p>Contenido en la pizarra</p>',resources:[]}})} />);
    fireEvent.keyDown(screen.getByLabelText('Mapa del valle'),{key:'e'});
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
    act(()=>state.current?.onPosition?.({x:NODO_ENTRANCE.x,y:NODO_ENTRANCE.y+15}));
    fireEvent.keyDown(screen.getByLabelText('Mapa del valle'),{key:'e'});
    expect(screen.getByLabelText('Interior del Nodo')).toBeVisible();
    act(()=>state.current?.onPosition?.({x:60,y:160}));
    fireEvent.keyDown(screen.getByLabelText('Interior del Nodo'),{key:'e'});
    expect(screen.getByLabelText('Interior del aula')).toBeVisible();
    act(()=>state.current?.onPosition?.({x:240,y:120}));
    fireEvent.click(screen.getByRole('button',{name:'Ver pizarra · E'}));
    expect(await screen.findByText('Contenido en la pizarra')).toBeVisible();
    expect(screen.queryByRole('link',{name:/Abrir contenido/})).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole('button',{name:'Cerrar y volver al juego'}));
    act(()=>state.current?.onExit?.());
    expect(screen.getByLabelText('Interior del Nodo')).toBeVisible();
    act(()=>state.current?.onExit?.());
    expect(screen.getByLabelText('Mapa del valle')).toBeVisible();
    view.unmount();
    render(<CourseMissionMap game={game} character={DEFAULT_CHARACTER} tutorial={{step:0,busy:false,error:'',onNext:vi.fn()}} />);
    expect(state.current?.movementLocked).toBe(true);
    expect(screen.queryByRole('group',{name:'Controles para caminar'})).not.toBeInTheDocument();
  });
});
